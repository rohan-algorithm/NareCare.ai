export function pickExercise(phase: CyclePhase): Exercise {
  const match = EXERCISES.find((e) => e.phase === phase);
  return match ?? EXERCISES.find((e) => e.phase === 'any')!;
}

export function todaysExercises(phase: CyclePhase, weekday = new Date().getDay()): Exercise[] {
  const ids = WEEKLY_MOVE_PLAN[weekday] ?? ['any_day_yoga'];
  const list = ids.map((id) => EXERCISES.find((e) => e.id === id)!).filter(Boolean);
  const primary = pickExercise(phase);
  if (!list.find((e) => e.id === primary.id)) list.unshift(primary);
  return list.slice(0, 3);
}

export function getExercise(id: string): Exercise | undefined {
  return EXERCISES.find((e) => e.id === id);
}

export function formatMoveDuration(m: MoveStep, lang: 'en' | 'hi' = 'en') {
  if (m.kind === 'reps') return lang === 'hi' ? `×${m.reps}` : `x${m.reps}`;
  const s = m.seconds ?? 0;
  if (s >= 60) {
    const min = Math.round(s / 60);
    return lang === 'hi' ? `${min} मि` : `${min} min`;
  }
  const mm = String(Math.floor(s / 60)).padStart(2, '0');
  const ss = String(s % 60).padStart(2, '0');
  return `${mm}:${ss}`;
}

export function sessionMoveCount(ex: Exercise) {
  return ex.moves?.length || ex.steps.length;
}
